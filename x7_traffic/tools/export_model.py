#!/usr/bin/env python3
"""Export the selected v018 traffic MOP tables, not instruction semantics.

Run from any directory. Normal builds use the committed generated header and
need only this app and the X7 SDK; regenerating uses the research repository.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from cmc8.versions.v018 import sequences

NAMES = ['NOP', 'LRM', 'SRD', 'LRI', 'INR', 'DCR', 'JSR', 'RSR',
         'BT0', 'BT1', 'BZ0', 'BZ1', 'JMP']


def mask(controls):
    return sum(1 << number for number in set(controls))


def main():
    lines = ['/* Generated by tools/export_model.py from research v018. */',
             '#ifndef TRAFFIC_TABLES_H', '#define TRAFFIC_TABLES_H',
             '#include <stdint.h>',
             'enum instruction { FETCH = -1, RESET = -2, ' + ', '.join(['NOP = 0', *NAMES[1:]]) + ' };',
             'static const char *const instruction_names[] = {' +
             ', '.join(f'"{name}"' for name in NAMES) + '};',
             'static const uint64_t reset_mops[8] = {',
             ', '.join(f'UINT64_C(0x{mask(row):x})' for row in sequences.RESET_CYCLE), '};',
             'static const uint64_t instruction_mops[][3][8] = {']
    for name in NAMES:
        lines.append('    { /* ' + name + ' */')
        rows = list(sequences.SEQUENCES[name])
        rows += [[()] * 8] * (3-len(rows))
        for row in rows:
            lines.append('        {' + ', '.join(f'UINT64_C(0x{mask(slot):x})' for slot in row) + '},')
        lines.append('    },')
    lines += ['};', 'static const uint64_t fetch_mops[8] = {',
              ', '.join(f'UINT64_C(0x{mask(slot):x})' for slot in sequences.LRS[0]), '};']
    source = json.loads((ROOT/'specification/traffic-program.json').read_text())
    lines.append('static const struct { uint16_t address; uint8_t value; } program_cells[] = {')
    lines += [f'    {{{int(cell["address"],8)}, {int(cell["byte"],8)}}},' for cell in source['cells']]
    lines += ['};', '#endif', '']
    output = ROOT/'x7_traffic/generated/tables.h'
    expected = '\n'.join(lines)
    if '--check' in sys.argv:
        if output.read_text() != expected:
            raise SystemExit('Stale generated/tables.h')
        print('v018 tables and literal traffic bytes are current')
    else:
        output.write_text(expected)


if __name__ == '__main__':
    main()
